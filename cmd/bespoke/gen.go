package main

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"text/template"

	"github.com/bketelsen/bespoke/internal/manifest"
)

const genHeader = "# GENERATED by bespoke — do not edit\n"

// cmdGen regenerates every derived artifact into dist/gen/ from the
// manifests (docs/specs/app-manifest.md: the manifest is the registry).
func cmdGen(args []string) error {
	cfg, err := loadConfig()
	if err != nil {
		return err
	}
	apps, warnings, err := manifest.LoadAll(".")
	if err != nil {
		return err
	}
	for _, w := range warnings {
		fmt.Fprintln(os.Stderr, "warning:", w)
	}
	return generate(cfg, apps)
}

func generate(cfg config, apps []manifest.App) error {
	if err := os.MkdirAll("dist/gen/units", 0o755); err != nil {
		return err
	}
	if err := writeUnits(apps); err != nil {
		return err
	}
	if err := writeCaddy(cfg, apps); err != nil {
		return err
	}
	if err := writeLitestream(apps); err != nil {
		return err
	}
	fmt.Println("generated: dist/gen/units/*.service dist/gen/bespoke.caddy dist/gen/litestream.yml")
	return nil
}

var unitTmpl = template.Must(template.New("unit").Parse(genHeader + `[Unit]
Description=Bespoke {{if .Platform}}platformd (dashboard/registry){{else}}app: {{.Slug}}{{end}}
After=network-online.target

[Service]
EnvironmentFile=%h/bespoke/env
{{if .Platform}}Environment=BESPOKE_ROOT=%h/bespoke
# systemd user units get a bare PATH; the LLM gateway execs copilot from
# ~/.local/bin (ADR-0009).
Environment=PATH=%h/.local/bin:/usr/local/bin:/usr/bin:/bin
ExecStart=%h/bespoke/bin/{{.Slug}} -listen ${BESPOKE_BIND_IP}:{{.Port}} -internal ${BESPOKE_BIND_IP}:4001
{{else}}ExecStart=%h/bespoke/bin/{{.Slug}} -listen ${BESPOKE_BIND_IP}:{{.Port}}
{{end}}
Restart=on-failure
RestartSec=2

[Install]
WantedBy=default.target
`))

func writeUnits(apps []manifest.App) error {
	type unit struct {
		Slug     string
		Port     int
		Platform bool
	}
	units := []unit{{Slug: "platformd", Port: 4000, Platform: true}}
	for _, a := range apps {
		units = append(units, unit{Slug: a.Slug, Port: a.Port})
	}
	for _, u := range units {
		f, err := os.Create(filepath.Join("dist/gen/units", "bespoke-"+u.Slug+".service"))
		if err != nil {
			return err
		}
		if err := unitTmpl.Execute(f, u); err != nil {
			f.Close()
			return err
		}
		f.Close()
	}
	if err := os.WriteFile("dist/gen/units/bespoke-litestream.service", []byte(genHeader+`[Unit]
Description=Bespoke Litestream replication (ADR-0007)
After=network-online.target

[Service]
EnvironmentFile=%h/bespoke/env
ExecStart=/usr/local/bin/litestream replicate -config %h/bespoke/litestream.yml
Restart=on-failure
RestartSec=5

[Install]
WantedBy=default.target
`), 0o644); err != nil {
		return err
	}
	// Deploy watcher (ADR-0023): a path unit outside every app's cgroup so
	// deploys survive the requesting app restarting. Enabled by deploy when
	// the host is bootstrapped for the builder plane.
	if err := os.WriteFile("dist/gen/units/bespoke-deploywatch.path", []byte(genHeader+`[Unit]
Description=Bespoke deploy spool watcher (ADR-0023)

[Path]
DirectoryNotEmpty=/var/lib/bespoke/spool/deploy

[Install]
WantedBy=default.target
`), 0o644); err != nil {
		return err
	}
	return os.WriteFile("dist/gen/units/bespoke-deploywatch.service", []byte(genHeader+`[Unit]
Description=Bespoke deploy from spool (ADR-0023)

[Service]
Type=oneshot
WorkingDirectory=%h/bespoke/repo
EnvironmentFile=%h/bespoke/env
Environment=BESPOKE_SPOOL=/var/lib/bespoke/spool
# just/go/golangci-lint via Homebrew; git and ssh from the system.
Environment=PATH=/home/linuxbrew/.linuxbrew/bin:%h/.local/bin:/usr/local/bin:/usr/bin:/bin
ExecStart=/var/lib/bespoke/bin/bespoke deploywatch
`), 0o644)
}

var caddyTmpl = template.Must(template.New("caddy").Parse(genHeader + `# Bespoke routes — imported from the edge host's Caddyfile:
#     import {{.EdgeCaddyFile}}
# Requires Caddy built with caddy-tailscale and caddy-dns/cloudflare, and
# CLOUDFLARE_API_TOKEN in Caddy's environment (deploy/README.md).

*.{{.Domain}}, {{.Domain}} {
	tls {
		dns cloudflare {env.CLOUDFLARE_API_TOKEN}
	}

	route {
		# SECURITY (ADR-0004): never trust identity headers from the client.
		request_header -Tailscale-User-Login
		request_header -Tailscale-User-Name

		tailscale_auth

		map {labels.{{.LabelIndex}}} {app_port} {
{{- range .Apps}}
			{{.Slug}} {{.Port}}
{{- end}}
			default 4000
		}

		reverse_proxy {{.SelfieTSIP}}:{app_port} {
			header_up Tailscale-User-Login {http.auth.user.tailscale_login}
			header_up Tailscale-User-Name  {http.auth.user.tailscale_name}
		}
	}
}
`))

func writeCaddy(cfg config, apps []manifest.App) error {
	f, err := os.Create("dist/gen/bespoke.caddy")
	if err != nil {
		return err
	}
	defer f.Close()
	return caddyTmpl.Execute(f, map[string]any{
		"Domain":        cfg.Domain,
		"SelfieTSIP":    cfg.SelfieTSIP,
		"EdgeCaddyFile": cfg.EdgeCaddyFile,
		// hello.bespoke.example.com: labels count from the right, so the app
		// label index equals the number of labels in the base domain.
		"LabelIndex": len(strings.Split(cfg.Domain, ".")),
		"Apps":       apps,
	})
}

var litestreamTmpl = template.Must(template.New("ls").Parse(genHeader + `# Litestream replication for every app database (ADR-0007). Runs on the app
# host; BESPOKE_DATA_DIR and BESPOKE_REPLICA_URL come from the litestream
# unit's environment (deploy/README.md).
dbs:
  - path: ${BESPOKE_DATA_DIR}/platformd.db
    replicas:
      - url: ${BESPOKE_REPLICA_URL}/platformd
{{- range .}}
  - path: ${BESPOKE_DATA_DIR}/{{.Slug}}.db
    replicas:
      - url: ${BESPOKE_REPLICA_URL}/{{.Slug}}
{{- end}}
`))

func writeLitestream(apps []manifest.App) error {
	f, err := os.Create("dist/gen/litestream.yml")
	if err != nil {
		return err
	}
	defer f.Close()
	return litestreamTmpl.Execute(f, apps)
}
